using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Module.PacketHandler.Filtering
{
    internal static class HostGeneration
    {
        public static SyntaxTree? Generate(IEnumerable<SyntaxTree> trees)
        {
            var entries = new List<(string FullName, string PropName)>();

            foreach (var tree in trees)
            {
                var root = tree.GetRoot();
                foreach (var cls in root.DescendantNodes().OfType<ClassDeclarationSyntax>())
                {
                    var ns = cls.Ancestors().OfType<NamespaceDeclarationSyntax>().FirstOrDefault()?.Name.ToString()
                             ?? GetFileScopedNamespace(cls) ?? "";

                    var implements = cls.BaseList?.Types
                        .Select(t => t.Type.ToString())
                        .Any(t => t is "ISessionState" or "Module.PacketHandler.Filtering.ISessionState") == true;

                    if (!implements) continue;

                    var name = cls.Identifier.Text;
                    var prop = name.EndsWith("State") ? name[..^5] : name;
                    var full = string.IsNullOrEmpty(ns) ? name : $"{ns}.{name}";
                    entries.Add((full, prop));
                }
            }

            if (entries.Count == 0) return null;

            var sb = new System.Text.StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("namespace NetGuard.Hot;");
            sb.AppendLine("public sealed class SessionHost");
            sb.AppendLine("{");
            foreach (var (full, prop) in entries)
                sb.AppendLine($"    public global::{full} {prop} {{ get; }} = new global::{full}();");
            sb.AppendLine("}");

            return CSharpSyntaxTree.ParseText(sb.ToString(), path: "SessionHost.g.cs");
        }

        private static string? GetFileScopedNamespace(SyntaxNode node)
        {
            // C# 10 file-scoped namespaces: walk up to CompilationUnit, find FileScopedNamespaceDeclarationSyntax
            var cu = node.AncestorsAndSelf().OfType<CompilationUnitSyntax>().FirstOrDefault();
            var fsn = cu?.Members.OfType<FileScopedNamespaceDeclarationSyntax>().FirstOrDefault();
            return fsn?.Name.ToString();
        }
    }
}